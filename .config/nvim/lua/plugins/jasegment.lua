-- 日本語上での W / E / B / aW / iW を文節単位にする。
--
-- 素の nvim は、ひらがな・カタカナ・漢字・記号をそれぞれ別の「単語クラス」として扱う
-- (charclass() が あ→12352 / ア→12448 / 漢→19968 と別値を返す)。そのため w は単語では
-- なく字種の切り替わりで止まる。「これは日本語の文章をカタカナで書くテストです。」では
--
--   日 | の | 文 | を | カ | で | 書 | く | テ | で | 。
--
-- の 11 箇所で止まり、どこに飛ぶか予測できない。逆に W は空白区切りなので、空白の無い
-- 日本語文は丸ごと 1 WORD になって行末まで飛ぶ。細かすぎるか粗すぎるかの二択になっている。
--
-- jasegment.vim は文節を推定して W/E/B をその単位にする。上の例なら
--
--   これは | 日本語の | 文章を | カタカナで | 書く | テストです。
--
-- の 6 文節で止まる。「1 文節 = 自立語 + 付属語」なので停止位置が意味の単位と一致し、
-- 何回押せば目的地かが読めるようになる。
--
-- w/b/e (小文字) は書き換えないので、コードを読むときの挙動は素のまま変わらない。
-- ASCII 上の W/E/B も空白区切りのままで、`xxxx.yyyy` の頭で E を押せば末尾の y に飛ぶ
-- (素の E と同じ)。iW も `xxxx.yyyy` 丸ごとを選ぶ。日本語の行でだけ挙動が変わる。
--
-- NOTE: 最終更新 2021 年の vimscript プラグインだが nvim 0.12 で動作確認済み。
-- 行単位のキャッシュを持つため、240 文字の行でも 1 モーション 0.02ms 程度で実害はない。
return {
  "deton/jasegment.vim",
  -- W/E/B はノーマルモードで即使うので、最初のバッファを読んだ時点で入れる
  event = { "BufReadPost", "BufNewFile" },
  init = function()
    -- 文節区切りの推定方法。knbc_bunsetu は同梱の TinySegmenter モデル (追加の
    -- 外部コマンド不要)。mecab / cabocha に切り替えると精度は上がるが、それぞれの
    -- コマンドを入れる必要がある。
    vim.g["jasegment#model"] = "knbc_bunsetu"

    -- 文節の開始位置に下線を出したい場合は 1 (移動時に更新) / 2 (InsertLeave でも更新)。
    -- 区切りを目で確認できるが、コードを読むときは煩いので既定の 0 のまま。
    vim.g["jasegment#highlight"] = 0

    -- W/E/B/aW/iW への割り当てはプラグイン既定のものをそのまま使う。
    -- 自分でキーを決めたい場合はここを 1 にして <Plug>JaSegmentMoveNW /
    -- <Plug>JaSegmentMoveNE / <Plug>JaSegmentMoveNB 等を貼る。
    vim.g.jasegment_no_default_key_mappings = 0
  end,
}
